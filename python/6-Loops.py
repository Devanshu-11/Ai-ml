# 1-For Loop
for i in range(5):
    print(i);

# 2-Loop through List 
fruits=["Apples","Orange","Banana"];
for fruit in fruits:
    print(fruit);

# 3-While Loop
count=1;
while count<=5:
    print(count);
    count=count+1;

# 4-Nested Loops
for i in range(5):
    for j in range(8):
        print(i,j);