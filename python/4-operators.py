# 1-Arithmetic Operators
a=10;
b=3;

print(a+b);

# Floor division
print(a//b); 
print(a/b);

# 2-Comparison Operators
a=5;
b=10;
print(a==b);
print(a!=b);

# 3-Logical Operators
x=5;
print(x>2 and x<10);

# 4-Membership Operators- check if the value is present in collection or not
nums=[1,2,3];

print(2 in nums);
print(5 not in nums);